export interface InventoryItem {
  id: string
  name: string
  category: "Dairy" | "Meat & Poultry" | "Produce" | "Grains & Bakery" | "Oils & Condiments" | "Beverages & Bar" | "Bakery & Sweets" | "Packaging" | string
  currentStock: number
  unit: string // "kg", "L", "pcs", "g", "packs", "cans", "bottles", "kegs"
  minimumStock: number // reorder trigger threshold
  optimalStock: number // ideal target stock
  costPerUnit: number // ₹ in INR
  supplier: string
  storageLocation: string
  lastRestocked: string // YYYY-MM-DD
  expiryDate?: string
  notes?: string
}

export interface StockMovement {
  id: string
  itemId: string
  itemName: string
  type: "RESTOCK" | "USAGE" | "WASTE" | "AUDIT"
  quantity: number // change amount
  previousStock: number
  newStock: number
  unit: string
  reason?: string
  performedBy?: string
  date: string // ISO timestamp
}

